import type { TokenFixture } from "./tok01.js";

/**
 * Language-pack fixtures (PRG-02, ADR-007).
 *
 * Same discipline as `tok01.ts` and for the same reason: every expectation here was
 * derived by reading the rules in `packages/engine/src/token-map.ts` and the profile
 * data in `packages/engine/src/profiles/catalog.ts`, and then confirmed against the
 * implementation. Nothing was captured from a run, because a captured expectation
 * only proves the code agrees with itself.
 *
 * Two fixture families live in this file:
 *
 *  - `PACK_FIXTURES` — one or more per pack, each aimed at the language's HARD case
 *    rather than its easy one. A pack whose fixture is `const x = 1` has not been
 *    tested.
 *  - `TOK_FIXTURE_004` — the ledger cites TOK-FIXTURE-004 against PRG-02, and the
 *    construct it pins is the one CNT-05 deferred on: what `#` MEANS. It is a
 *    single text run tokenized under four packs, with four different answers, so
 *    the fixture cannot pass by accident.
 *
 * `language` is the id a content record would declare (so an alias like `jsx` is
 * itself under test); `pack` is the canonical pack it must resolve to. The runner
 * uses `tokenizePacked`, never `tokenize`, for the reason in
 * `packages/engine/src/profiles/resolve.ts`: PRG-01's id table predates these packs.
 */
export interface PackFixture extends TokenFixture {
  /** The canonical pack id `language` must resolve to. */
  readonly pack: string;
  /**
   * Why this snippet, and anything a reader would otherwise reverse-engineer.
   * A `note` that says BLOCKED names a lexer gap in
   * docs/profiles/prg02-language-packs.md §6 — the fixture pins what the lexer does
   * TODAY so the day the gap closes, the change is visible in the diff.
   */
  readonly note?: string;
}

