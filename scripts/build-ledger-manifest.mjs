#!/usr/bin/env node
/**
 * Regenerate the expected-ID manifest for check-ledger.mjs from the spec
 * sources, and report the diff.
 *
 * The manifest exists because the first version of the ledger gate could not
 * tell "a row was deleted" from "the count was updated honestly" — the attack
 * pass deleted BIZ-05 and then the entire NFR prefix, updated the counts to
 * match, and the gate passed both times. Self-consistency is not integrity.
 *
 * Run:  node scripts/build-ledger-manifest.mjs          (report only)
 *       node scripts/build-ledger-manifest.mjs --write  (rewrite the manifest)
 *
 * A deletion therefore needs a deliberate manifest edit, which is a reviewable
 * diff rather than a silent omission.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const MANIFEST = join(root, "scripts", "ledger-manifest.json");
const write = process.argv.includes("--write");

/** Prefixes that are real requirements. PRG-06..09 do not exist in the spec. */
const PREFIXES = [
  "ENG",
  "MOD",
  "LRN",
  "PRG",
  "ANA",
  "CNT",
  "INT",
  "CMP",
  "MOT",
  "USR",
  "CUS",
  "A11Y",
  "LOC",
  "MOB",
  "WEL",
  "BIZ",
  "OPS",
  "ADM",
  "EXT",
  "MST",
  "RET",
  "NFR",
];

/**
 * Sources, in the order they are scanned. A later source does not override an
 * earlier one; IDs are unioned.
 */
const SOURCES = [
  "docs/spec/master-spec-v1.md",
  "docs/spec/retention-and-mastery-playbook.md",
  "docs/spec/implementation-guide.md",
  "docs/BUILD-ROADMAP-START-TO-END.md",
  "docs/MASTER-BUILD-CONTRACT.md",
];

/**
 * ID namespaces that appear in the sources but are NOT requirements. Excluded
 * so the manifest does not demand a row for a science fact or a pain point.
 *
 *   PP-nn    pain points (evidence, master spec §2.2)
 *   SC-n     science facts (§2.1, retention §3)
 *   P1..P7   personas · A1..A8 assumptions
 *   E-n      validation experiments (master spec §13) AND Chapter 4 §4.9 Named
 *            Edge Cases — two unrelated schemes sharing one prefix
 *   ER-n     retention experiments · T1..T5 threats
 *   ID-nn    legacy v0.2 idea IDs
 *   D-n / Dn  decisions
 *   R0-nn, M0-nn..M8-nn, RET-M-nn, V1-nn  implementation task IDs
 *   S1..S6   feasibility spikes
 *   H-n      hypotheses · NFR-nn IS a requirement (kept)
 */
const EXCLUDE_PREFIX =
  /^(PP-\d+|SC-\d+|P\d+|A\d+|E-\d+|ER-\d+|T\d+|ID-\d+|D-[\w-]+|D\d+|R0-\d+|M\d-\d+|RET-M-\d+|V1-\d+|S\d+|H\d+)$/;

/**
 * Requirement IDs are zero-padded to two digits (ENG-01, RET-21). Decision IDs
 * in the same documents are single-digit (RET-1 .. RET-9 in the retention
 * playbook, D-RET-1 .. D-RET-9 elsewhere), so a single-digit suffix is not a
 * requirement row.
 */
const SINGLE_DIGIT = /^[A-Z0-9]+-\d$/;

/**
 * IDs that appear in the sources as cross-references but have no row, because
 * the spec never defines them. Each is documented in the ledger's
 * "data-integrity warnings". Adding one here means deciding the spec is wrong,
 * which is a deliberate act — not a way to silence a missing row.
 */
const KNOWN_NON_EXISTENT = new Map([
  [
    "PRG-09",
    "MOD-03 cites (PRG-09) for IDE-realism options, but the spec defines no " +
      "PRG-09 row. PRG-06/07/08 are absent too. The real row is PRG-15. " +
      "Ledger warning #1.",
  ],
]);

const idRe = /\b([A-Z][A-Z0-9]{1,5})-(\d{1,3})\b/g;

const found = new Map(); // id -> Set of source files
for (const rel of SOURCES) {
  const abs = join(root, rel);
  if (!existsSync(abs)) {
    console.error(`missing source: ${rel}`);
    process.exit(1);
  }
  const text = readFileSync(abs, "utf8");
  for (const m of text.matchAll(idRe)) {
    const id = `${m[1]}-${m[2]}`;
    if (EXCLUDE_PREFIX.test(id)) continue;
    if (SINGLE_DIGIT.test(id)) continue;
    if (KNOWN_NON_EXISTENT.has(id)) continue;
    if (!PREFIXES.includes(m[1])) continue;
    if (!found.has(id)) found.set(id, new Set());
    found.get(id).add(rel);
  }
}

const ids = [...found.keys()].sort();
const manifest = {
  $comment:
    "Generated by scripts/build-ledger-manifest.mjs. Every ID here must have a row in docs/FEATURE-LEDGER.md. A deletion requires editing this file on purpose.",
  generatedFrom: SOURCES,
  count: ids.length,
  ids,
};

if (write) {
  writeFileSync(MANIFEST, `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
  console.log(`wrote ${MANIFEST} with ${ids.length} IDs`);
} else {
  console.log(`manifest would contain ${ids.length} IDs from ${SOURCES.length} sources`);
  const byPrefix = new Map();
  for (const id of ids) {
    const p = id.split("-")[0];
    byPrefix.set(p, (byPrefix.get(p) ?? 0) + 1);
  }
  for (const p of PREFIXES) {
    const n = byPrefix.get(p) ?? 0;
    console.log(`  ${p}: ${n}${n === 0 ? "   <-- none found in sources" : ""}`);
  }
}
